def get_sg_total_dict():
    """Return dict of player_name -> sg_total per round."""
    return {name: sg for name, sg in SG_TOTAL_2025}


def sg_to_score(sg_total, sg_min=-0.5, sg_max=2.8):
    """Convert SG Total per round to a 0-100 score.

    +2.8 (Scheffler-level) → 100
    +1.5 (top 10) → ~61
    +0.5 (top 50) → ~30
     0.0 (average) → ~15
    -0.5 (below avg) → 0
    """
    score = (sg_total - sg_min) / (sg_max - sg_min) * 100
    return max(0, min(100, round(score, 1)))
