def normalize_stat(value, stat_type):
    """Normalize a stat to a 0-100 scale based on stat type.

    Higher score = better performance for all metrics.
    """
    # Define min/max ranges for each stat type
    ranges = {
        # Strokes Gained (higher is better)
        "sg_ott": (-0.5, 1.1),
        "sg_app": (-0.3, 1.4),
        "sg_arg": (-0.2, 0.4),
        "sg_putt": (-0.3, 0.35),
        # Traditional stats
        "driving_dist": (275, 325),  # yards (higher is better)
        "fairways_pct": (48, 75),     # % (higher is better)
        "gir_pct": (55, 75),          # % (higher is better)
        "scrambling_pct": (47, 68),   # % (higher is better)
        "putting_avg": (29.8, 27.8),  # putts/round (lower is better, so reversed)
        # Scoring stats
        "birdie_pct": (12, 25),       # % (higher is better)
        "par5_scoring": (4.8, 4.35),  # avg score (lower is better, so reversed)
        "bogey_avoid_pct": (66, 85),  # % (higher is better)
    }

    if stat_type not in ranges:
        return 50.0  # Default middle value

    min_val, max_val = ranges[stat_type]

    # Handle inverted scales (where lower is better)
    if min_val > max_val:
        # Reverse the calculation for inverted scales
        score = (min_val - value) / (min_val - max_val) * 100
    else:
        score = (value - min_val) / (max_val - min_val) * 100

    return max(0, min(100, round(score, 1)))


def get_normalized_stats(player_name):
    """Get all stats for a player normalized to 0-100 scale."""
    stats = get_player_advanced_stats(player_name)
    if not stats:
        return None

    return {
        stat_type: normalize_stat(value, stat_type)
        for stat_type, value in stats.items()
    }
